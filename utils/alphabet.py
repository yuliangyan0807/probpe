BLOSUM62 = np.array(
    [list(map(int, line.split())) for line in _BLOSUM_ROWS.strip().splitlines()],
    dtype=np.float64,
)
BLOSUM_MAX = float(BLOSUM62.max())
EPS = 1e-6


def aa_idx(seq: str) -> np.ndarray:
    return np.array([AA_INDEX[c] for c in seq], dtype=np.int32)


def blosum_positive_subs(aa_i: int) -> list[int]:
    row = BLOSUM62[aa_i]
    return [j for j in range(N_AA) if j != aa_i and row[j] > 0]


def sim_blosum(w: str, w_prime: str) -> float:
    s = 0.0
    for a, b in zip(w, w_prime):
        s += BLOSUM62[AA_INDEX[a], AA_INDEX[b]]
    return s / (BLOSUM_MAX * len(w))


def js_bernoulli_vec(p: np.ndarray, q: np.ndarray) -> np.ndarray:
    p = np.clip(p, EPS, 1.0 - EPS)
    q = np.clip(q, EPS, 1.0 - EPS)
    m = 0.5 * (p + q)

    def kl(a: np.ndarray, b: np.ndarray) -> np.ndarray:
        return a * np.log(a / b) + (1.0 - a) * np.log((1.0 - a) / (1.0 - b))

    return 0.5 * kl(p, m) + 0.5 * kl(q, m)
